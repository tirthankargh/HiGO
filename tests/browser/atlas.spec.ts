import { test, expect } from '@playwright/test';
const drang='RGI2000-v7.0-G-14-26914';
const first='RGI2000-v7.0-G-14-00001';
test('atlas renders local tiles, filters, selects records, and opens the journal',async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const summary=await (await request.get('/api/atlas')).json();expect(summary.summary.count).toBe(56149);
  expect(summary.results).toHaveLength(30);
  const record=await (await request.get(`/api/atlas/${drang}`)).json();expect(record.source_date).toBe('2000-09-04');expect(record.area).toBeCloseTo(68.362,2);
  expect((await request.get('/api/atlas?bbox=NaN,2,3,4')).status()).toBe(400);
  expect((await request.get('/api/atlas/tiles/11/0/0')).status()).toBe(400);
  const tile=await request.get('/api/atlas/tiles/0/0/0');expect(tile.status()).toBe(200);expect((await tile.body()).length).toBeGreaterThan(1000);
  await page.setViewportSize({width:1440,height:1000});await page.goto('/atlas');
  await expect(page.getByTestId('atlas-map')).toHaveAttribute('data-ready','true');
  await expect(page.locator('.atlas-map-notice')).toHaveCount(0);
  await page.screenshot({path:'test-results/atlas-desktop.png',fullPage:true});
  await page.getByLabel('Search glaciers by name or RGI ID').fill('Drang');
  await expect(page.locator('.atlas-result')).toHaveCount(1);
  await page.locator('.atlas-result').click();await expect(page.locator('.atlas-detail h2')).toHaveText('Drang Drung');
  await expect(page).toHaveURL(new RegExp(`glacier=${drang}`));
  await expect(page.locator('.atlas-detail')).toContainText('Provisional association');
  await expect(page.locator('.atlas-map-caption')).toContainText('RGI inventory outlines');
  await page.screenshot({path:'test-results/atlas-selected.png',fullPage:true});
  await page.getByRole('link',{name:'Open photo journal'}).click();await expect(page).toHaveURL(/glaciers\/drang-drang/);
  await page.goto(`/atlas?glacier=${drang}`);await expect(page.locator('.atlas-detail h2')).toHaveText('Drang Drung');
  await page.getByRole('button',{name:'Close glacier details'}).click();await expect(page.locator('.atlas-detail')).toHaveCount(0);
  await page.getByLabel('Atlas region').selectOption('15');await expect(page.locator('.atlas-result').first()).toContainText('South Asia East');
  await page.getByLabel('Search glaciers by name or RGI ID').fill('no-such-glacier-123');await expect(page.getByText('No glaciers found here.')).toBeVisible();
  await page.getByRole('button',{name:'Show available coverage'}).click();await expect(page.locator('.atlas-result').first()).toContainText('Drang Drung');
  await page.getByLabel('Inventory',{exact:true}).uncheck();await expect(page.getByLabel('Inventory',{exact:true})).not.toBeChecked();
  await page.getByLabel('Inventory',{exact:true}).check();
  await page.setViewportSize({width:390,height:844});await page.goto(`/atlas?glacier=${drang}`);await expect(page.locator('.atlas-detail h2')).toHaveText('Drang Drung');
  await expect(page.getByTestId('atlas-map')).toHaveAttribute('data-ready','true');
  await expect(page.locator('.atlas-map-caption')).toContainText('RGI inventory outlines');
  await expect(page.locator('.atlas-result').first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/atlas-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});

test('inventory contribution stays private until review and survives a reload without a journal assignment',async({page,request})=>{
  await page.goto(`/atlas?glacier=${first}`);await expect(page.locator('.atlas-detail')).toContainText('No reviewed photographs');
  await page.getByRole('link',{name:'Contribute to this glacier'}).click();
  await expect(page.locator('.contribution-form')).toContainText(first);
  await page.getByLabel('Choose photograph',{exact:true}).setInputFiles('Panchinala/DSCF1629.jpg');
  await expect(page.getByText('No capture date found.',{exact:false})).toBeVisible();
  await page.getByLabel('A note from this moment').fill('Inventory association test photo');
  await page.getByLabel('Contact email').fill('atlas-private@example.test');
  await page.getByRole('checkbox',{name:/I took this photograph/}).check();
  await page.getByRole('button',{name:'Send for review'}).click();await expect(page).toHaveURL(/submission\//);
  const pending=await (await request.get(`/api/atlas/${first}`)).json();expect(pending.photos).toHaveLength(0);
  await page.goto('/admin');await page.getByLabel('Admin password').fill('higo-browser-test-password');await page.getByRole('button',{name:'Sign in',exact:false}).click();
  await page.getByRole('link',{name:/Inventory association test photo/}).click();
  await expect(page.getByLabel('RGI inventory ID',{exact:false})).toHaveValue(first);
  await expect(page.getByLabel('Journal glacier')).toHaveValue('');
  const id=page.url().split('/').pop()!;
  expect((await request.get(`/api/media/${id}`)).status()).toBe(404);
  await page.getByLabel('Review status').selectOption('approved');await page.getByRole('button',{name:'Save review'}).click();await expect(page.getByRole('status')).toContainText('Observation saved');
  const approved=await (await request.get(`/api/atlas/${first}`)).json();expect(approved.photos).toHaveLength(1);expect(JSON.stringify(approved)).not.toContain('atlas-private');expect(approved.photos[0].contact).toBeUndefined();
  await page.goto(`/atlas?glacier=${first}`);await expect(page.locator('.atlas-linked-photos')).toContainText('Inventory association test photo');await page.reload();await expect(page.locator('.atlas-linked-photos')).toContainText('Inventory association test photo');
  expect((await request.get(`/api/media/${id}?variant=original`)).status()).toBe(404);
  await page.goto(`/admin/observations/${id}`);await page.getByLabel('Review status').selectOption('pending');await page.getByRole('button',{name:'Save review'}).click();await expect(page.getByRole('status')).toContainText('Observation saved');
  expect((await (await request.get(`/api/atlas/${first}`)).json()).photos).toHaveLength(0);
});
